#!/usr/bin/env node
// wire-export — ONE model in, four engines out (operator 2026-09-15: "Designs should be wireframe that can
// feed Unreal and Unity with one step conversion we create from scratch (to ensure Vision-2525 intent)").
//
// This is U-WF-05 made real. The reference pattern, docs/security-2525/xbat-wireframe/, is a HAND-WRITTEN
// quadruple: the same silhouette table typed four times in Python, OBJ, C# and C++. That cannot stay true —
// the fourth copy drifts the first time someone edits one. Here the WireModel is the only truth and the four
// files are output; editing an output is meaningless because --check regenerates and refuses on drift.
//
// AXES ARE NOT AN AFTERTHOUGHT. The model frame is ENU metres (east, north, up). Each target gets the
// conversion its engine actually wants, written down rather than assumed:
//   .py / .obj  X=east  Y=north Z=up      metres   (Z-up, right-handed — matplotlib and the existing OBJ)
//   .cs (Unity) X=east  Y=up    Z=north   metres   (Y-up, left-handed)
//   .cpp (UE)   X=north Y=east  Z=up      CENTIMETRES (Z-up, left-handed, UE's unit is the cm)
//
//   node scripts/wire-export.mjs <model.json> [--out <dir>] [--check]
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const AXES = {
  py:    { name: "Python/OBJ (Z-up, m)",  scale: 1,   map: (v) => [v[0], v[1], v[2]] },
  obj:   { name: "OBJ (Z-up, m)",         scale: 1,   map: (v) => [v[0], v[1], v[2]] },
  unity: { name: "Unity (Y-up, m)",       scale: 1,   map: (v) => [v[0], v[2], v[1]] },
  unreal:{ name: "Unreal (Z-up, cm)",     scale: 100, map: (v) => [v[1], v[0], v[2]] },
};
const f6 = (n) => (Math.round(n * 1e6) / 1e6).toFixed(6);

/** The geometry, index-free: every segment as its two endpoints, endpoints ordered, list sorted. */
export function canonicalSegments(m) {
  const out = m.edges.map(([a, b]) => {
    const p = m.vertices[a], q = m.vertices[b];
    const A = `${f6(p[0])},${f6(p[1])},${f6(p[2])}`, B = `${f6(q[0])},${f6(q[1])},${f6(q[2])}`;
    return A <= B ? `${A}|${B}` : `${B}|${A}`;
  });
  out.sort();
  return out;
}
export const canonicalHash = (m) => crypto.createHash("sha256").update(canonicalSegments(m).join("\n")).digest("hex");

const segmentsOf = (m) => m.edges.map(([a, b]) => [m.vertices[a], m.vertices[b]]);
const conv = (v, t) => AXES[t].map(v).map((n) => n * AXES[t].scale);
const header = (m, target) =>
  `eXeL WIREFRAME-CORE · ${m.meta.name} · v${m.meta.version} r${m.meta.revision}\n` +
  `${m.meta.stamp}\nGenerated by scripts/wire-export.mjs from ${m.meta.id}.json — DO NOT EDIT; edit the model.\n` +
  `Axes: ${AXES[target].name}. Vertices ${m.vertices.length} · segments ${m.edges.length}.\n` +
  `Source: ${m.meta.source ?? "—"}`;

// ── .py — matplotlib Line3DCollection ────────────────────────────────────────────────────────────
function toPy(m) {
  const segs = segmentsOf(m).map(([a, b]) => `    ((${conv(a,"py").map(f6).join(", ")}), (${conv(b,"py").map(f6).join(", ")})),`).join("\n");
  return `"""\n${header(m, "py")}\n"""\nimport matplotlib.pyplot as plt\nfrom mpl_toolkits.mplot3d.art3d import Line3DCollection\n\n` +
    `SEGMENTS = [\n${segs}\n]\n\n\ndef render(ax=None, color="#00FFFF", lw=0.6):\n` +
    `    """Draw the wireframe. Edges only — there is no surface to shade."""\n` +
    `    if ax is None:\n        fig = plt.figure(figsize=(10, 8))\n        ax = fig.add_subplot(111, projection="3d")\n` +
    `    ax.add_collection3d(Line3DCollection(SEGMENTS, colors=color, linewidths=lw))\n` +
    `    pts = [p for s in SEGMENTS for p in s]\n` +
    `    for dim, setter in enumerate((ax.set_xlim, ax.set_ylim, ax.set_zlim)):\n` +
    `        lo = min(p[dim] for p in pts); hi = max(p[dim] for p in pts)\n        pad = (hi - lo) * 0.05 or 1.0\n        setter(lo - pad, hi + pad)\n` +
    `    ax.set_box_aspect((1, 1, 1)); ax.set_facecolor("black"); ax.set_axis_off()\n    return ax\n\n\n` +
    `if __name__ == "__main__":\n    render()\n    plt.show()\n`;
}

// ── .obj — line-only OBJ (v + l), the interchange every DCC reads ────────────────────────────────
function toObj(m) {
  const lines = [header(m, "obj").split("\n").map((l) => `# ${l}`).join("\n")];
  for (const v of m.vertices) lines.push(`v ${conv(v, "obj").map(f6).join(" ")}`);
  for (const g of m.groups) {
    lines.push(`o ${g.id}`, `# role ${g.role} · kind ${g.kind} · lod ${g.lod}`);
    for (let i = g.edge0; i < g.edgeN; i++) lines.push(`l ${m.edges[i][0] + 1} ${m.edges[i][1] + 1}`);
  }
  return lines.join("\n") + "\n";
}

// ── .cs — Unity MonoBehaviour ────────────────────────────────────────────────────────────────────
function toCs(m) {
  const cls = m.meta.id.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toUpperCase()) + "Wireframe";
  const segs = segmentsOf(m).map(([a, b]) => `        new[]{ new Vector3(${conv(a,"unity").map(f6).join("f, ")}f), new Vector3(${conv(b,"unity").map(f6).join("f, ")}f) },`).join("\n");
  return `// ${header(m, "cs" in AXES ? "cs" : "unity").split("\n").join("\n// ")}\nusing System.Collections.Generic;\nusing UnityEngine;\n\n` +
    `public class ${cls} : MonoBehaviour\n{\n    public Color LineColor = new Color(0f, 1f, 1f);\n    public float LineWidth = 0.02f;\n\n` +
    `    // ENU metres -> Unity (X=east, Y=up, Z=north). Edges only: there are no faces to build.\n` +
    `    public static readonly List<Vector3[]> Segments = new List<Vector3[]>\n    {\n${segs}\n    };\n\n` +
    `    void Start()\n    {\n        var mat = new Material(Shader.Find("Sprites/Default"));\n` +
    `        for (int i = 0; i < Segments.Count; i++)\n        {\n            var go = new GameObject($"seg{i}");\n` +
    `            go.transform.SetParent(transform, false);\n            var lr = go.AddComponent<LineRenderer>();\n` +
    `            lr.useWorldSpace = false; lr.positionCount = 2;\n            lr.SetPosition(0, Segments[i][0]); lr.SetPosition(1, Segments[i][1]);\n` +
    `            lr.startWidth = lr.endWidth = LineWidth;\n            lr.material = mat; lr.startColor = lr.endColor = LineColor;\n        }\n    }\n}\n`;
}

// ── .cpp/.h — Unreal AActor ──────────────────────────────────────────────────────────────────────
function toCpp(m) {
  const cls = "A" + m.meta.id.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toUpperCase()) + "WireframeActor";
  const segs = segmentsOf(m).map(([a, b]) => `    { FVector(${conv(a,"unreal").map(f6).join("f, ")}f), FVector(${conv(b,"unreal").map(f6).join("f, ")}f) },`).join("\n");
  const h = `// ${header(m, "unreal").split("\n").join("\n// ")}\n#pragma once\n\n#include "CoreMinimal.h"\n#include "GameFramework/Actor.h"\n#include "${cls.slice(1)}.generated.h"\n\n` +
    `USTRUCT()\nstruct FWireSegment { GENERATED_BODY() FVector A; FVector B; };\n\n` +
    `UCLASS()\nclass ${cls} : public AActor\n{\n    GENERATED_BODY()\npublic:\n    ${cls}();\n` +
    `    UPROPERTY(EditAnywhere) FColor LineColor = FColor(0, 255, 255);\n    UPROPERTY(EditAnywhere) float LineThickness = 1.0f;\n` +
    `    virtual void Tick(float DeltaSeconds) override;\n    static const TArray<FWireSegment>& Segments();\n};\n`;
  const cpp = `// ${header(m, "unreal").split("\n").join("\n// ")}\n#include "${cls.slice(1)}.h"\n#include "DrawDebugHelpers.h"\n\n` +
    `// ENU metres -> Unreal (X=north, Y=east, Z=up) in CENTIMETRES.\nstatic const TArray<FWireSegment> GSegments = {\n${segs}\n};\n\n` +
    `const TArray<FWireSegment>& ${cls}::Segments() { return GSegments; }\n\n` +
    `${cls}::${cls}() { PrimaryActorTick.bCanEverTick = true; }\n\n` +
    `void ${cls}::Tick(float DeltaSeconds)\n{\n    Super::Tick(DeltaSeconds);\n    const FTransform& X = GetActorTransform();\n` +
    `    for (const FWireSegment& S : GSegments)\n    {\n        DrawDebugLine(GetWorld(), X.TransformPosition(S.A), X.TransformPosition(S.B),\n` +
    `                      LineColor, false, -1.f, 0, LineThickness);\n    }\n}\n`;
  return { h, cpp };
}

export function exportAll(m) {
  const { h, cpp } = toCpp(m);
  const hash = canonicalHash(m);
  return {
    [`${m.meta.id}.py`]: toPy(m),
    [`${m.meta.id}.obj`]: toObj(m),
    [`${m.meta.id}.cs`]: toCs(m),
    [`${m.meta.id}.h`]: h,
    [`${m.meta.id}.cpp`]: cpp,
    [`${m.meta.id}.hash.json`]: JSON.stringify({
      id: m.meta.id, version: m.meta.version, revision: m.meta.revision, stamp: m.meta.stamp,
      vertices: m.vertices.length, edges: m.edges.length, groups: m.groups.length, overlays: m.overlays.length,
      sha256: hash, axisMap: { py: "X=east,Y=north,Z=up,m", obj: "X=east,Y=north,Z=up,m", unity: "X=east,Y=up,Z=north,m", unreal: "X=north,Y=east,Z=up,cm" },
      generator: "scripts/wire-export.mjs",
    }, null, 2) + "\n",
  };
}

// ── CLI ──────────────────────────────────────────────────────────────────────────────────────────
if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const src = args.find((a) => !a.startsWith("--"));
  if (!src) { console.error("usage: wire-export.mjs <model.json> [--out dir] [--check]"); process.exit(1); }
  const outDir = args.includes("--out") ? args[args.indexOf("--out") + 1] : path.dirname(src);
  const check = args.includes("--check");
  const model = JSON.parse(fs.readFileSync(src, "utf8"));
  const files = exportAll(model);
  let drift = 0;
  for (const [name, body] of Object.entries(files)) {
    const dest = path.join(outDir, name);
    if (check) {
      const have = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
      if (have !== body) { drift++; console.error(`DRIFT ${name}${have === null ? " (missing)" : ""}`); }
    } else {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, body);
    }
  }
  const hash = canonicalHash(model);
  if (check) {
    if (drift) { console.error(`\nREFUSED — ${drift} file(s) differ from the model. Regenerate; never hand-edit an output.`); process.exit(1); }
    console.log(`wire-export --check OK · ${model.meta.id} · ${model.edges.length} segments · sha256 ${hash.slice(0, 16)}…`);
  } else {
    console.log(`wire-export ${model.meta.id} → ${outDir}/ · ${model.vertices.length} verts · ${model.edges.length} segments · sha256 ${hash.slice(0, 16)}…`);
  }
}
