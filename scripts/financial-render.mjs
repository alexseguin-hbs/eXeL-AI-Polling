#!/usr/bin/env node
// FINANCIAL-2525 · ONE EDITABLE SOURCE → every generated view (the drone-render pattern, verbatim in spirit).
// ==========================================================================================================
// docs/financial-2525/financial-2525.v.000.json is the only file a human edits. This script renders:
//   docs/financial-2525/CRS_FINANCIAL-2525.md      the step-by-step CRS ladder (FIN-01 … FIN-13)
//   docs/financial-2525/README.md                  the domain's front page (MoT law, calendar, escrow, example)
//   docs/financial-2525/DECISIONS_REGISTER.md      every DECLARED / OPERATOR decision with its basis
//   frontend/lib/financial-2525/domain.gen.ts      the typed module the app imports (the app never reads docs/)
// `--check` re-renders in memory and refuses on any drift, so a generated view can never disagree with its
// source. Run it in test:ci (tests/financial-crs.test.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "docs/financial-2525/financial-2525.v.000.json");
const d = JSON.parse(fs.readFileSync(SRC, "utf8"));

const CHECK = process.argv.includes("--check");
const STATUSES = ["draft", "approved", "implemented", "verified", "superseded", "out-of-scope"];
const SECTIONS = {
  I: "Humanity First", II: "R-CORE", III: "COMM", IV: "LINK", V: "EDGE", VI: "SYNC / Replay",
  VII: "UCRS", VIII: "Rehearsal", IX: "Trust", X: "Governance", XI: "SSSES", XII: "Flywheel", XIII: "Translation",
};

const head = (title) =>
  `<!-- GENERATED by scripts/financial-render.mjs from docs/financial-2525/financial-2525.v.000.json — do not hand-edit. -->\n` +
  `# ${title}\n\n**${d.project.stamp} · Version ${d.project.version} · revision ${d.project.revision}** · ${d.project.family}\n\n` +
  `> ${d.project.disclaimer}\n\n`;

function renderCrs() {
  let s = head("CRS · Financial-2525");
  s += `Handoff: \`${d.project.handoff}\` \`sha256 ${d.project.handoffSha256}\`\n\n`;
  s += `Id law (docs/vision-2525/CRS-GOVERNANCE-PLAN.md): \`FIN-##.##\`, two digits never letters; parents are permanent; sub-ids append only; a changed requirement is **superseded**, never rewritten.\n\n`;
  s += `## The ladder — one step per Vision • 2525 section\n\n`;
  s += `| CRS | Requirement | § | R-CORE | Phase | Status | Verified by |\n|---|---|---|---|---|---|---|\n`;
  for (const r of d.crs) s += `| \`${r.id}\` | ${r.title} | ${r.section} ${SECTIONS[r.section] ?? ""} | ${r.mode} | ${r.phase} | ${r.status} | \`${r.verify}\` |\n`;
  s += `\n## Every row in full\n\n`;
  for (const r of d.crs) {
    s += `### ${r.id} — ${r.title}\n\n**Statement.** ${r.statement}\n\n| field | value |\n|---|---|\n`;
    s += `| Input / Output | \`${r.in}\` → \`${r.out}\` |\n| Vision • 2525 | § ${r.section} — ${SECTIONS[r.section] ?? ""} |\n`;
    s += `| U-WF trace | ${(r.uwf ?? []).map((u) => `\`${u}\``).join(" · ") || "—"} |\n| R-CORE mode | ${r.mode} |\n| De-risk phase | ${r.phase} |\n`;
    s += `| Declared metric M | ${r.metric} |\n| DTM target | ${r.dtm} |\n| Stretch | ${r.stretch} |\n| Verification | \`${r.verify}\` |\n| Status | **${r.status}** |\n\n`;
  }
  s += `## Revisions (append only)\n\n| revision | date | kind | commit | why |\n|---|---|---|---|---|\n`;
  for (const r of d.revisions) s += `| ${r.revision} | ${r.date} | ${r.kind} | \`${r.commit}\` | ${r.why} |\n`;
  return s + `\n`;
}

