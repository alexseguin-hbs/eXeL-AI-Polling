function segmentSlide(id) {
  const s = seg(id), n = nba(s.nba), nose = d.nose.find((x) => x.segment === id);
  return (
    `**${s.name}** · weights X ${s.x_operationalImpact} · Y ${s.y_humanCoordination} · Z ${s.z_replayLearning} (${s.weightsStatus}) · NBA **${n.name}**\n\n` +
    `**Need.** ${nose.needs}\n\n**Outcomes.**\n\n${li(nose.outcomes)}\n**Solution.** ${nose.solution}\n\n` +
    `**Evidence.**\n\n| claim | status | experiment |\n|---|---|---|\n` +
    nose.evidence.map((e) => `| ${e.claim} | ${e.status} | ${e.experiment} |`).join("\n") + "\n\n" +
    `**NBA positioning.** ${n.positioning} (${n.status})\n`);
}

function valueTable(v) {
  const s = seg(v.segment), n = nba(v.nba);
  return (
    `#### ${v.segment} — ${s.name} vs ${n.name}\n\n` +
    `NBA outcome cost today: ${v.nbaOutcomeCost}\n\n` +
    `| # | differentiator | NBA today | value driver | metric (S16) | status |\n|---:|---|---|---|---|---|\n` +
    v.rows.map((r) => `| ${r.n} | ${r.differentiator} | ${r.nbaToday} | ${r.valueDriver} | ${r.metric} | ${r.status} |`).join("\n") + "\n\n" +
    `Total customer value: ${v.totalCustomerValue} · value capture: ${v.valueCapture} · WTP range: ${v.wtpRange}\n`);
}

