#!/usr/bin/env node
// DE-RISKING STRATEGIES · ONE EDITABLE SOURCE → the gate-review document.
// ======================================================================
// docs/drs/drs.v00.00.json is the only file a human edits. This script renders:
//   docs/drs/DE-RISKING_STRATEGIES_GATE_REVIEW.md   S1–S20 on the G1–G7 ladder, three NOSE statements,
//                                                    three differentiator / value-equation tables, DRS-01…13,
//                                                    risks, roadmap, gate exit, and the list of what stays UNPROVEN.
//
// `--check` re-renders in memory and refuses on any drift (the drone-render pattern), so the document can never
// disagree with its source. Runs in test:ci as test:drs-render.
//
// Evidence law (from the source): every statement is SOURCED, DECLARED, HYPOTHESIS or UNPROVEN, and no dollar
// figure is written until a pilot measures it. The renderer enforces the second half mechanically: a value row
// or financial line that carries a digit next to a $ sign refuses to render.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "docs/drs/drs.v00.00.json");
const OUT_REL = "docs/drs/DE-RISKING_STRATEGIES_GATE_REVIEW.md";
const d = JSON.parse(fs.readFileSync(SRC, "utf8"));
const CHECK = process.argv.includes("--check");

const STATUSES = ["draft", "approved", "implemented", "verified", "superseded", "out-of-scope"];
const EVIDENCE = ["SOURCED", "DECLARED", "HYPOTHESIS", "UNPROVEN"];
const STAGES = d.stageGate.stages;

const li = (xs) => xs.map((x) => `- ${x}`).join("\n") + "\n";
const oli = (xs) => xs.map((x, i) => `${i + 1}. ${x}`).join("\n") + "\n";
const seg = (id) => d.segments.find((s) => s.id === id);
const nba = (id) => d.nbas.find((n) => n.id === id);
const slide = (n) => d.slides.find((s) => s.n === n);

const head = () =>
  `<!-- GENERATED by scripts/drs-render.mjs from docs/drs/drs.v00.00.json — do not hand-edit. -->\n` +
  `# ${d.project.name} — Gate Review\n\n` +
  `**Version ${d.project.version} · revision ${d.project.revision}** · Project # ${d.project.projectNumber} (${d.project.projectNumberNote}) · ` +
  `Business: ${d.project.business}\n\n` +
  `**Stage:** ${d.project.stage} · **Decision requested:** ${d.project.decisionRequested}\n\n` +
  `Created ${d.project.created} · ${d.project.author}\n\n` +
  `> **Evidence law.** ${d.evidenceLaw}\n\n`;

// Each slide's body is rendered from the section of the source it names, so the deck and the data cannot drift.
function slideBody(n) {
  switch (n) {
    case "S1": return (
      `**Decision requested.** ${d.project.decisionRequested}\n\n` +
      `**Three segments, three next-best alternatives.**\n\n| segment | name | NBA | X · Y · Z (weights) | weights |\n|---|---|---|---|---|\n` +
      d.segments.map((s) => `| ${s.id} | ${s.name} | ${nba(s.nba).name} | ${s.x_operationalImpact} · ${s.y_humanCoordination} · ${s.z_replayLearning} | ${s.weightsStatus} |`).join("\n") + "\n\n" +
      `**The wedge (what the NBAs do not do).**\n\n${li(d.wedge)}\n` +
      `**What stays unproven at this gate.**\n\n${li(d.unproven)}`);
    case "S2": return (
      `**Sources.**\n\n| id | source | where |\n|---|---|---|\n` +
      d.sources.map((s) => `| ${s.id} | ${s.title} | \`${s.where}\`${s.sha256 ? ` · sha256 \`${s.sha256.slice(0, 12)}…\`` : ""} |`).join("\n") + "\n\n" +
      `**Stage-gate discipline (${d.stageGate.source}).** ${STAGES.map((s, i) => `${d.stageGate.gates[i]} ${s}`).join(" → ")}.\n\n${d.stageGate.loop}\n\n` +
      `**Resilience heritage.** ${d.conops.resilienceHeritage}\n`);
    case "S3": return (
      `**Axes.**\n\n| axis | meaning |\n|---|---|\n| X | ${d.axes.x} |\n| Y | ${d.axes.y} |\n| Z | ${d.axes.z} |\n\n` +
      `**Segments and weights (1–10, ${d.segments[0].weightsStatus}).**\n\n| segment | name | X operational impact | Y human coordination | Z replay / learning | paired NBA |\n|---|---|---:|---:|---:|---|\n` +
      d.segments.map((s) => `| ${s.id} | ${s.name} | ${s.x_operationalImpact} | ${s.y_humanCoordination} | ${s.z_replayLearning} | ${nba(s.nba).name} |`).join("\n") + "\n");
    case "S4": return (
      `**Before.**\n\n${oli(d.conops.before)}\n**During.**\n\n${oli(d.conops.during)}\n**Plan revision.** ${d.conops.revision}\n\n**After.**\n\n${oli(d.conops.after)}`);
    case "S5": return (
      `**Personas.**\n\n| command | responders | affected |\n|---|---|---|\n| ${d.personas.command.join(" · ")} | ${d.personas.responders.join(" · ")} | ${d.personas.affected.join(" · ")} |\n\n` +
      `**Principle.** ${d.personas.principle}\n\n**The three needs, one per segment.**\n\n` +
      d.nose.map((n) => `- **${n.segment} — ${seg(n.segment).name}.** ${n.needs}`).join("\n") + "\n");
    case "S6": return (
      `**Four layers, four owners.**\n\n| layer | what it holds | owner |\n|---|---|---|\n` +
      d.architecture.map((a) => `| ${a.layer} | ${a.items.join(" · ")} | ${a.owner} |`).join("\n") + "\n\n" +
      `**Not differentiators (the NBAs already do these).** ${d.notDifferentiators.join(" · ")}.\n`);
    case "S7": return (
      `**Command.** ${d.personas.command.join(" · ")}\n\n**Responders.** ${d.personas.responders.join(" · ")}\n\n**Affected.** ${d.personas.affected.join(" · ")}\n\n` +
      `**Workflow.** ${d.conops.during.join(" → ")}.\n\n**Authority.** ${d.personas.principle}\n`);
    case "S8": return segmentSlide("SEG-1");
    case "S9": return segmentSlide("SEG-2");
    case "S10": return segmentSlide("SEG-3");
    case "S11": return (
      `**The chain.**\n\n${oli(d.rcore.chain)}\n**${d.rcore.statement}**\n\n${d.rcore.law}\n`);
    case "S12": return (
      `| NBA | segment | strong at | positioning | status |\n|---|---|---|---|---|\n` +
      d.nbas.map((n) => `| ${n.name} | ${n.segment} | ${n.strongAt.join(" · ")} | ${n.positioning} | ${n.status} |`).join("\n") + "\n\n" +
      `**The wedge.** ${d.wedge.join(" · ")}.\n`);
    case "S13": return d.valueTables.map(valueTable).join("\n");
    case "S14": return (
      `**${d.wtpMetrics.law}**\n\n` +
      d.segments.map((s) => `**${s.id} — ${s.name}.** ${d.wtpMetrics[s.id].join(" · ")}`).join("\n\n") + "\n\n" +
      `| segment | NBA outcome cost today | total customer value | value capture | WTP range |\n|---|---|---|---|---|\n` +
      d.valueTables.map((v) => `| ${v.segment} | ${v.nbaOutcomeCost} | ${v.totalCustomerValue} | ${v.valueCapture} | ${v.wtpRange} |`).join("\n") + "\n");
    case "S15": {
      const plans = d.scenarios.filter((s) => s.name);
      const shows = d.scenarios.find((s) => s.shows);
      return `| plan | posture |\n|---|---|\n` + plans.map((p) => `| **${p.name}** | ${p.items.join(" · ")} |`).join("\n") + `\n\n**Each plan shows:** ${shows.shows}\n`;
    }
    case "S16": return (
      `**Loop.** ${d.evidenceProgram.loop}\n\n**The thirteen columns of the pilot's record.**\n\n${oli(d.evidenceProgram.metrics)}\n> ${d.evidenceProgram.note}\n\n` +
      `**Experiments by segment (from the NOSE statements).**\n\n| segment | claim | status | experiment |\n|---|---|---|---|\n` +
      d.nose.flatMap((n) => n.evidence.map((e) => `| ${n.segment} | ${e.claim} | ${e.status} | ${e.experiment} |`)).join("\n") + "\n");
    case "S17": return (
      `| line | value |\n|---|---|\n| Value creation | ${d.financial.valueCreation} |\n| Value capture | ${d.financial.valueCapture} |\n` +
      `| Commercial model | ${d.financial.commercialModel.join(" · ")} |\n| 3-year NPV | ${d.financial.npv} |\n| IRR | ${d.financial.irr} |\n` +
      `| COGS | ${d.financial.cogs} |\n| MSRP | ${d.financial.msrp} |\n| Margin | ${d.financial.margin} |\n\n> ${d.financial.note}\n`);
    case "S18": return d.roadmap.map((r) => `**${r.mvp}** · ${r.when} · ${r.stage}\n\n${li(r.items)}`).join("\n");
    case "S19": return (
      `| id | risk | issue | countermeasure / mitigation | owner |\n|---|---|---|---|---|\n` +
      d.risks.map((r) => `| ${r.id} | ${r.risk} | ${r.issue} | ${r.mitigation} | ${r.owner} |`).join("\n") + "\n");
    case "S20": return (
      `**Decision requested.** ${d.project.decisionRequested}\n\n**Gate exit — what must be true to pass G2 → G3.**\n\n${li(d.gateExit)}\n` +
      `**Explicitly unproven (no number is written for these until measured).**\n\n${li(d.unproven)}`);
    default: return "";
  }
}

function segmentSlide(id) {
  const s = seg(id), n = nba(s.nba), nose = d.nose.find((x) => x.segment === id);
  return (
    `**${s.name}** · weights X ${s.x_operationalImpact} · Y ${s.y_humanCoordination} · Z ${s.z_replayLearning} (${s.weightsStatus}) · NBA **${n.name}**\n\n` +
    `**Need.** ${nose.needs}\n\n**Outcomes.**\n\n${li(nose.outcomes)}\n**Solution.** ${nose.solution}\n\n` +
    `**Evidence.**\n\n| claim | status | experiment |\n|---|---|---|\n` +
    nose.evidence.map((e) => `| ${e.claim} | ${e.status} | ${e.experiment} |`).join("\n") + "\n\n" +
    `**NBA positioning.** ${n.positioning} (${n.status})\n`);
}

function valueTable(v) {
  const s = seg(v.segment), n = nba(v.nba);
  return (
    `#### ${v.segment} — ${s.name} vs ${n.name}\n\n` +
    `NBA outcome cost today: ${v.nbaOutcomeCost}\n\n` +
    `| # | differentiator | NBA today | value driver | metric (S16) | status |\n|---:|---|---|---|---|---|\n` +
    v.rows.map((r) => `| ${r.n} | ${r.differentiator} | ${r.nbaToday} | ${r.valueDriver} | ${r.metric} | ${r.status} |`).join("\n") + "\n\n" +
    `Total customer value: ${v.totalCustomerValue} · value capture: ${v.valueCapture} · WTP range: ${v.wtpRange}\n`);
}

function renderDoc() {
  let s = head();
  s += `## Contents\n\n`;
  s += `| slide | title | stage | evidence |\n|---|---|---|---|\n`;
  for (const sl of d.slides) s += `| ${sl.n} | [${sl.title}](#${sl.n.toLowerCase()}--${sl.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}) | ${sl.stage} | ${sl.evidence} |\n`;
  s += `\nThen: the three NOSE statements · the CRS ladder DRS-01…13 · revisions.\n\n`;
  for (const sl of d.slides) {
    s += `---\n\n## ${sl.n} — ${sl.title}\n\n*Stage ${sl.stage} · evidence ${sl.evidence} · reads \`${sl.fields}\`*\n\n${slideBody(sl.n)}\n`;
  }
  s += `---\n\n## The three NOSE statements\n\n`;
  s += `Need · Outcome · Solution · Evidence, one per segment — the shape the Innovation Pod's project brief carries.\n\n`;
  for (const n of d.nose) {
    const sg = seg(n.segment);
    s += `### ${n.segment} — ${sg.name}\n\n| | |\n|---|---|\n| **Need** | ${n.needs} |\n| **Outcome** | ${n.outcomes.join(" · ")} |\n| **Solution** | ${n.solution} |\n`;
    s += `| **Evidence** | ${n.evidence.map((e) => `${e.claim} — **${e.status}** (${e.experiment})`).join(" · ")} |\n\n`;
  }
  s += `---\n\n## CRS ladder — DRS-01 … DRS-13\n\n`;
  s += `Id law: \`DRS-##\`, two digits never letters; parents permanent; a changed requirement is superseded, never rewritten. Every row names its stage on the G1–G7 ladder, its evidence state and the Vision • 2525 section it serves.\n\n`;
  s += `| step | id | requirement | stage | status | evidence | Vision • 2525 | segment |\n|---:|---|---|---|---|---|---|---|\n`;
  for (const r of d.crs) s += `| ${r.step} | \`${r.id}\` | ${r.name} | ${r.stage} | ${r.status} | ${r.evidence} | ${r.vision} | ${r.segment} |\n`;
  s += `\n### Every row in full\n\n`;
  for (const r of d.crs) s += `**${r.id} — ${r.name}**\n\n- IN: ${r.in}\n- OUT: ${r.out}\n\n`;
  s += `---\n\n## Revisions (append only)\n\n| revision | date | kind | commit | why |\n|---|---|---|---|---|\n`;
  for (const r of d.revisions) s += `| ${r.revision} | ${r.date} | ${r.kind} | \`${r.commit}\` | ${r.why} |\n`;
  return s + `\n`;
}

// ── invariants asserted BEFORE anything is written (a malformed source refuses, never persists) ──
function assertSource() {
  const fail = (m) => { console.error(`drs-render: ${m}`); process.exit(1); };
  if (!/^\d{2}\.\d{2}$/.test(d.project.version)) fail(`version must be XX.YY, got ${d.project.version}`);
  if (!/^\d\.\d{3}$/.test(d.project.revision)) fail(`revision must be X.YYY, got ${d.project.revision}`);
  if (d.stageGate.stages.length !== 7 || d.stageGate.gates.length !== 7) fail(`the ladder is seven stages and seven gates`);
  // S1…S20, each exactly once, in order, each on a real stage
  const want = Array.from({ length: 20 }, (_, i) => `S${i + 1}`);
  const got = d.slides.map((s) => s.n);
  if (got.join(",") !== want.join(",")) fail(`slides must be S1…S20 once each in order, got ${got.join(",")}`);
  for (const s of d.slides) {
    if (!s.title || !s.fields || !s.evidence) fail(`${s.n} is missing title / fields / evidence`);
    const stages = s.stage.split("→").map((x) => x.trim());
    for (const st of stages) if (!STAGES.includes(st)) fail(`${s.n} stage "${st}" is not on the ladder`);
    if (!EVIDENCE.some((e) => s.evidence.startsWith(e))) fail(`${s.n} evidence "${s.evidence}" must start with one of ${EVIDENCE.join(", ")}`);
  }
  // three segments, three paired NBAs (a fourth NBA may be a partner, never a segment's pair), NOSE and value tables per segment
  if (d.segments.length !== 3) fail(`three segments, got ${d.segments.length}`);
  for (const s of d.segments) {
    if (!nba(s.nba)) fail(`${s.id} pairs an NBA that does not exist: ${s.nba}`);
    for (const k of ["x_operationalImpact", "y_humanCoordination", "z_replayLearning"]) {
      if (!(Number.isInteger(s[k]) && s[k] >= 1 && s[k] <= 10)) fail(`${s.id}.${k} must be an integer 1–10`);
    }
    if (!d.nose.find((n) => n.segment === s.id)) fail(`${s.id} has no NOSE statement`);
    if (!d.valueTables.find((v) => v.segment === s.id)) fail(`${s.id} has no value table`);
    if (!d.wtpMetrics[s.id]?.length) fail(`${s.id} has no WTP metrics`);
  }
  if (d.nose.length !== 3) fail(`three NOSE statements, got ${d.nose.length}`);
  for (const n of d.nose) {
    if (!n.needs || !n.outcomes?.length || !n.solution || !n.evidence?.length) fail(`NOSE ${n.segment} is missing needs / outcomes / solution / evidence`);
    for (const e of n.evidence) if (!EVIDENCE.includes(e.status)) fail(`NOSE ${n.segment} evidence status "${e.status}" is not one of ${EVIDENCE.join(", ")}`);
  }
  if (d.valueTables.length !== 3) fail(`three value tables, got ${d.valueTables.length}`);
  for (const v of d.valueTables) {
    if (!(v.rows.length >= 5 && v.rows.length <= 7)) fail(`value table ${v.segment} must carry 5–7 rows, got ${v.rows.length}`);
    v.rows.forEach((r, i) => { if (r.n !== i + 1) fail(`value table ${v.segment} row ${i + 1} is numbered ${r.n}`); });
    for (const r of v.rows) if (!EVIDENCE.includes(r.status)) fail(`value table ${v.segment} row ${r.n} status "${r.status}" is not evidence-law`);
    if (!nba(v.nba)) fail(`value table ${v.segment} names NBA ${v.nba}, which does not exist`);
  }
  // no invented dollar figure anywhere: "$" may only be followed by " —" (or "/" for a per-unit driver name)
  const money = JSON.stringify([d.valueTables, d.financial, d.wtpMetrics, d.nose]);
  const bad = money.match(/\$\s?\d[\d,.]*\s?[kKmMbB]?/);
  if (bad) fail(`a dollar figure was written before a pilot measured it: "${bad[0]}" — the evidence law forbids it`);
  // CRS rows: id law, unique, in/out ids, stage on the ladder, status in the six, evidence in the four
  const seen = new Set();
  d.crs.forEach((r, i) => {
    if (!/^DRS-\d{2}$/.test(r.id)) fail(`${r.id} breaks the id law (DRS-##)`);
    if (seen.has(r.id)) fail(`${r.id} is declared twice`);
    seen.add(r.id);
    if (r.step !== i + 1) fail(`${r.id} step ${r.step} is out of order`);
    if (!r.in.startsWith(`${r.id}.`) || !r.in.includes(".IN") || !r.out.startsWith(`${r.id}.`) || !r.out.includes(".OUT")) fail(`${r.id} in/out ids must be ${r.id}.##.IN / .OUT`);
    if (!STAGES.includes(r.stage)) fail(`${r.id} stage "${r.stage}" is not on the ladder`);
    if (!STATUSES.includes(r.status)) fail(`${r.id} status "${r.status}" is not one of ${STATUSES.join(", ")}`);
    if (!EVIDENCE.some((e) => r.evidence.startsWith(e))) fail(`${r.id} evidence "${r.evidence}" must start with one of ${EVIDENCE.join(", ")}`);
    for (const f of ["name", "vision", "segment"]) if (!r[f]) fail(`${r.id} is missing ${f}`);
  });
  if (d.crs.length !== 13) fail(`thirteen CRS rows (one per Vision • 2525 section), got ${d.crs.length}`);
  if (d.unproven.length !== 4) fail(`the operator named four unproven items, got ${d.unproven.length}`);
  // revisions strictly increase; the last is the project's; a release cites a commit or says PENDING (filled after the artefact commit)
  let last = 0;
  for (const r of d.revisions) {
    const n = Math.round(Number(r.revision) * 1000);
    if (!(n > last)) fail(`revisions must strictly increase: ${r.revision} follows ${last / 1000}`);
    last = n;
    if (r.kind === "release" && !/^([0-9a-f]{7,40}|PENDING)$/.test(r.commit ?? "")) fail(`release ${r.revision} must cite a commit (or PENDING until the artefact commit exists)`);
  }
  if (d.revisions[d.revisions.length - 1].revision !== d.project.revision) fail(`project.revision ${d.project.revision} is not the last entry in revisions[]`);
}

assertSource();
const body = renderDoc();
const badWord = body.match(/\b(undefined|NaN)\b/);
if (badWord) { console.error(`drs-render: would render "${badWord[1]}" — a field name is wrong; nothing written`); process.exit(1); }

const abs = path.join(ROOT, OUT_REL);
const cur = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
if (CHECK) {
  if (cur !== body) { console.error(`drs-render --check: ${OUT_REL} is stale (re-run \`node scripts/drs-render.mjs\`)`); process.exit(1); }
  console.log(`drs-render --check: ${OUT_REL} matches the source (${d.slides.length} slides · ${d.crs.length} CRS · ${d.nose.length} NOSE · ${d.valueTables.reduce((a, v) => a + v.rows.length, 0)} value rows · revision ${d.project.revision})`);
} else {
  if (cur !== body) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, body); console.log(`wrote ${OUT_REL}`); }
  console.log(`drs-render: ${d.slides.length} slides · ${d.crs.length} CRS rows · revision ${d.project.revision}`);
}
