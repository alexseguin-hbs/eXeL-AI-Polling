#!/usr/bin/env node
// DE-RISKING STRATEGIES · ONE EDITABLE SOURCE → the gate-review document.
// ======================================================================
// docs/drs/drs.v00.00.json is the only file a human edits. This script renders:
//   docs/drs/DE-RISKING_STRATEGIES_GATE_REVIEW.md   S1–S20 on the G1–G7 ladder, three NOSE statements,
//                                                    three differentiator / value-equation tables, DRS-01…13,
//                                                    risks, roadmap, gate exit, and the list of what stays UNPROVEN.
//
// `--check` re-renders in memory and refuses on any drift (the drone-render pattern), so the document can never
// disagree with its source. Runs in test:ci as test:drs-render.
//
// Evidence law (from the source): every statement is SOURCED, DECLARED, HYPOTHESIS or UNPROVEN, and no dollar
// figure is written until a pilot measures it. The renderer enforces the second half mechanically: a value row
// or financial line that carries a digit next to a $ sign refuses to render.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "docs/drs/drs.v00.00.json");
const OUT_REL = "docs/drs/DE-RISKING_STRATEGIES_GATE_REVIEW.md";
const d = JSON.parse(fs.readFileSync(SRC, "utf8"));
const CHECK = process.argv.includes("--check");

const STATUSES = ["draft", "approved", "implemented", "verified", "superseded", "out-of-scope"];
const EVIDENCE = ["SOURCED", "DECLARED", "HYPOTHESIS", "UNPROVEN"];
const STAGES = d.stageGate.stages;

const li = (xs) => xs.map((x) => `- ${x}`).join("\n") + "\n";
const oli = (xs) => xs.map((x, i) => `${i + 1}. ${x}`).join("\n") + "\n";
const seg = (id) => d.segments.find((s) => s.id === id);
// 0.006 · two segment sets: the ARCHIVED DRS-attach exploration (SEG-1..3, NOSE / value tables) and the CURRENT v0.8.2 set (SEG-4..6).
const ARCHIVED = () => d.segments.filter((s) => /^ARCHIVED/.test(s.status || ""));
const CURRENT = () => d.segments.filter((s) => /^CURRENT/.test(s.status || ""));
const nba = (id) => d.nbas.find((n) => n.id === id);
const slide = (n) => d.slides.find((s) => s.n === n);

const head = () =>
  `<!-- GENERATED by scripts/drs-render.mjs from docs/drs/drs.v00.00.json — do not hand-edit. -->\n` +
  `# ${d.project.name} — Gate Review\n\n` +
  `**Version ${d.project.version} · revision ${d.project.revision}** · Project # ${d.project.projectNumber} (${d.project.projectNumberNote}) · ` +
  `Business: ${d.project.business}\n\n` +
  `**Stage:** ${d.project.stage} · **Decision requested:** ${d.project.decisionRequested}\n\n` +
  `Created ${d.project.created} · ${d.project.author}\n\n` +
  `> **Evidence law.** ${d.evidenceLaw}\n\n`;

