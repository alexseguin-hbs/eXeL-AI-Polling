#!/usr/bin/env node
/**
 * gen-rcore-revisions — extract each 2525 surface's REVISION RECORD into a small typed module the
 * client can import, WITHOUT pulling a 200 KB source document into the bundle.
 *
 * WHY THIS EXISTS (R-CORE, Stage 1). The R-CORE version-history badge needs each surface's own
 * revisions to compare them. Two sources hold that truth today:
 *   · SoI-2525  → docs/drs/drs.v00.00.json `revisions[]`  (a 200 KB+ living document — we take ONLY
 *                 the revisions array, never the whole file, so nothing heavy reaches the client)
 *   · Drone-2525 → docs/traceability/drone-2525.ledger.json (the append-only {section,route,entries} ledger)
 *
 * Both source files are OWNED BY OTHER WORKFLOWS (the PRJ-34 rounds own drs.v00.00.json). This script
 * only READS them and writes MY OWN generated modules under lib/2525-core. Re-run after either source
 * moves:  node scripts/gen-rcore-revisions.mjs
 *
 * The generated files are committed snapshots — deterministic, gate-checked — not a live read.
 */
import fs from "node:fs";
import path from "node:path";

const FRONTEND = path.resolve(new URL("..", import.meta.url).pathname);
const ROOT = path.resolve(FRONTEND, "..");
const OUT_DIR = path.join(FRONTEND, "lib", "2525-core");

const HEADER = (src) =>
  `// GENERATED by frontend/scripts/gen-rcore-revisions.mjs — DO NOT EDIT BY HAND.\n` +
  `// Source (read-only, owned by another workflow): ${src}\n` +
  `// Re-run: node scripts/gen-rcore-revisions.mjs\n`;

// ── SoI-2525 · the DRS revisions[] only (never the whole document) ────────────────────────────────
{
  const src = path.join(ROOT, "docs/drs/drs.v00.00.json");
  const drs = JSON.parse(fs.readFileSync(src, "utf8"));
  const revisions = (Array.isArray(drs.revisions) ? drs.revisions : []).map((r) => ({
    revision: String(r.revision ?? ""),
    date: String(r.date ?? ""),
    kind: String(r.kind ?? ""),
    why: String(r.why ?? ""),
    commit: String(r.commit ?? ""),
  }));
  const body =
    HEADER("docs/drs/drs.v00.00.json (revisions[] only)") +
    `\nimport type { DrsRevisionInput } from "@/lib/2525-core/revisions";\n\n` +
    `/** SoI-2525 DRS revision record — ${revisions.length} revisions, extracted at build time. */\n` +
    `export const SOI_DRS_REVISIONS: DrsRevisionInput[] = ${JSON.stringify(revisions, null, 2)};\n`;
  fs.writeFileSync(path.join(OUT_DIR, "soi-drs-revisions.gen.ts"), body);
  console.log(`soi-drs-revisions.gen.ts ← ${revisions.length} DRS revisions`);
}

// ── Drone-2525 · the append-only traceability ledger, verbatim ────────────────────────────────────
{
  const src = path.join(ROOT, "docs/traceability/drone-2525.ledger.json");
  const led = JSON.parse(fs.readFileSync(src, "utf8"));
  const ledger = {
    section: String(led.section ?? ""),
    route: String(led.route ?? ""),
    note: String(led.note ?? ""),
    entries: (Array.isArray(led.entries) ? led.entries : []).map((e) => ({
      rev: e.rev,
      date: String(e.date ?? ""),
      kind: String(e.kind ?? ""),
      text: String(e.text ?? ""),
      commit: String(e.commit ?? ""),
    })),
  };
  const body =
    HEADER("docs/traceability/drone-2525.ledger.json") +
    `\nimport type { LedgerInput } from "@/lib/2525-core/revisions";\n\n` +
    `/** Drone-2525 append-only traceability ledger — ${ledger.entries.length} entries, extracted at build time. */\n` +
    `export const DRONE_LEDGER: LedgerInput = ${JSON.stringify(ledger, null, 2)};\n`;
  fs.writeFileSync(path.join(OUT_DIR, "drone-ledger.gen.ts"), body);
  console.log(`drone-ledger.gen.ts ← ${ledger.entries.length} ledger entries`);
}

console.log("gen-rcore-revisions OK");
