#!/usr/bin/env node
/**
 * gen-rcore-revisions — extract each 2525 surface's REVISION RECORD into a small typed module the
 * client can import, WITHOUT pulling a 200 KB source document into the bundle.
 *
 * WHY THIS EXISTS (R-CORE, Stage 1). The R-CORE version-history badge needs each surface's own
 * revisions to compare them. Two sources hold that truth today:
 *   · SoI-2525  → docs/drs/drs.v00.00.json `revisions[]`  (a 200 KB+ living document — we take ONLY
 *                 the revisions array, never the whole file, so nothing heavy reaches the client)
 *   · Drone-2525 → docs/traceability/drone-2525.ledger.json (the append-only {section,route,entries} ledger)
 *
 * Both source files are OWNED BY OTHER WORKFLOWS (the PRJ-34 rounds own drs.v00.00.json). This script
 * only READS them and writes MY OWN generated modules under lib/2525-core. Re-run after either source
 * moves:  node scripts/gen-rcore-revisions.mjs
 *
 * The generated files are committed snapshots — deterministic, gate-checked — not a live read.
 *
 *   node scripts/gen-rcore-revisions.mjs            writes them
 *   node scripts/gen-rcore-revisions.mjs --check    exits 1 if ANY of them is stale, changing nothing
 *
 * WHY --check EXISTS (r.210, 2026-10-14). Until now this script ran NOWHERE — not in a package script, not
 * in prebuild, not in CI, not in any workflow. It was manual only, so a ledger could be appended to and the
 * committed .gen.ts left behind, and EVERY R-CORE panel would quietly show a history that is not the ledger,
 * with nothing in the repository to catch it. The idiom is the one scripts/manta-render.mjs already uses.
 */
import fs from "node:fs";
import path from "node:path";

const FRONTEND = path.resolve(new URL("..", import.meta.url).pathname);
const ROOT = path.resolve(FRONTEND, "..");
const OUT_DIR = path.join(FRONTEND, "lib", "2525-core");

// --check writes nothing and exits 1 on the first file that differs from what this run would write.
const CHECK = process.argv.includes("--check");
let stale = 0;
const emit = (file, body, note) => {
  const p = path.join(OUT_DIR, file);
  if (CHECK) {
    const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "";
    if (cur !== body) { stale++; console.error(`STALE  lib/2525-core/${file} — re-run node scripts/gen-rcore-revisions.mjs`); }
    else console.log(`ok     ${file} ← ${note}`);
  } else {
    fs.writeFileSync(p, body);
    console.log(`${file} ← ${note}`);
  }
};

const HEADER = (src) =>
  `// GENERATED by frontend/scripts/gen-rcore-revisions.mjs — DO NOT EDIT BY HAND.\n` +
  `// Source (read-only, owned by another workflow): ${src}\n` +
  `// Re-run: node scripts/gen-rcore-revisions.mjs\n`;

// ── SoI-2525 · the DRS revisions[] only (never the whole document) ────────────────────────────────
{
  const src = path.join(ROOT, "docs/drs/drs.v00.00.json");
  const drs = JSON.parse(fs.readFileSync(src, "utf8"));
  const revisions = (Array.isArray(drs.revisions) ? drs.revisions : []).map((r) => ({
    revision: String(r.revision ?? ""),
    date: String(r.date ?? ""),
    kind: String(r.kind ?? ""),
    why: String(r.why ?? ""),
    commit: String(r.commit ?? ""),
  }));
  const body =
    HEADER("docs/drs/drs.v00.00.json (revisions[] only)") +
    `\nimport type { DrsRevisionInput } from "@/lib/2525-core/revisions";\n\n` +
    `/** SoI-2525 DRS revision record — ${revisions.length} revisions, extracted at build time. */\n` +
    `export const SOI_DRS_REVISIONS: DrsRevisionInput[] = ${JSON.stringify(revisions, null, 2)};\n`;
  emit("soi-drs-revisions.gen.ts", body, `${revisions.length} DRS revisions`);
}

// ── Drone-2525 · the append-only traceability ledger, verbatim ────────────────────────────────────
{
  const src = path.join(ROOT, "docs/traceability/drone-2525.ledger.json");
  const led = JSON.parse(fs.readFileSync(src, "utf8"));
  const ledger = {
    section: String(led.section ?? ""),
    route: String(led.route ?? ""),
    note: String(led.note ?? ""),
    entries: (Array.isArray(led.entries) ? led.entries : []).map((e) => ({
      rev: e.rev,
      date: String(e.date ?? ""),
      kind: String(e.kind ?? ""),
      text: String(e.text ?? ""),
      commit: String(e.commit ?? ""),
    })),
  };
  const body =
    HEADER("docs/traceability/drone-2525.ledger.json") +
    `\nimport type { LedgerInput } from "@/lib/2525-core/revisions";\n\n` +
    `/** Drone-2525 append-only traceability ledger — ${ledger.entries.length} entries, extracted at build time. */\n` +
    `export const DRONE_LEDGER: LedgerInput = ${JSON.stringify(ledger, null, 2)};\n`;
  emit("drone-ledger.gen.ts", body, `${ledger.entries.length} ledger entries`);
}

// ── Stage 2 · one traceability ledger per additional surface, verbatim ─────────────────────────────
// Each is an append-only {section,route,note,entries[]} ledger I author under docs/traceability, mirroring
// the Drone-2525 shape. These are MY OWN files (not owned by another workflow), seeded from real commits.
// Emitting a small typed snapshot per surface keeps the client import identical to the Stage-1 pattern.
const STAGE2_LEDGERS = [
  { file: "security-2525.ledger.json", constName: "SECURITY_LEDGER", out: "security-ledger.gen.ts" },
  { file: "settings.ledger.json",      constName: "SETTINGS_LEDGER", out: "settings-ledger.gen.ts" },
  { file: "easter-egg.ledger.json",    constName: "EASTER_EGG_LEDGER", out: "easter-egg-ledger.gen.ts" },
  { file: "architect-2525.ledger.json", constName: "ARCHITECT_LEDGER", out: "architect-ledger.gen.ts" },
  { file: "celestial-2525.ledger.json", constName: "CELESTIAL_LEDGER", out: "celestial-ledger.gen.ts" },
  { file: "financial-2525.ledger.json", constName: "FINANCIAL_LEDGER", out: "financial-ledger.gen.ts" }, // Financial-2525 (operator 2026-09-30, v.000_r.001)
];
for (const { file, constName, out } of STAGE2_LEDGERS) {
  const src = path.join(ROOT, "docs/traceability", file);
  const led = JSON.parse(fs.readFileSync(src, "utf8"));
  const ledger = {
    section: String(led.section ?? ""),
    route: String(led.route ?? ""),
    note: String(led.note ?? ""),
    entries: (Array.isArray(led.entries) ? led.entries : []).map((e) => ({
      rev: e.rev,
      date: String(e.date ?? ""),
      kind: String(e.kind ?? ""),
      text: String(e.text ?? ""),
      commit: String(e.commit ?? ""),
    })),
  };
  const body =
    HEADER(`docs/traceability/${file}`) +
    `\nimport type { LedgerInput } from "@/lib/2525-core/revisions";\n\n` +
    `/** ${ledger.section} append-only traceability ledger — ${ledger.entries.length} entries, extracted at build time. */\n` +
    `export const ${constName}: LedgerInput = ${JSON.stringify(ledger, null, 2)};\n`;
  emit(out, body, `${ledger.entries.length} ledger entries`);
}

if (CHECK && stale) { console.error(`\ngen-rcore-revisions --check: ${stale} generated file(s) are behind their ledger`); process.exit(1); }
console.log(CHECK ? "gen-rcore-revisions --check OK · every generated module matches its ledger" : "gen-rcore-revisions OK");
