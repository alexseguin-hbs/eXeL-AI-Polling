#!/usr/bin/env node
// gen-i18n-index — writes lib/i18n-sign/index.ts from the language files that EXIST (lib/i18n-sign/<code>.ts), so the loader
// never imports a file that is not there: a language whose file has not landed yet simply falls back to English until it does.
// Runs at predev and prebuild; hand-edits to index.ts are overwritten. Operator 2026-09-09: every UX string in 33 languages.
import fs from "node:fs"; import path from "node:path";
const dir = path.join(process.cwd(), "lib", "i18n-sign");
// a file counts only when it is COMPLETE: it ends with the export line and carries at least 300 keys (a translator still writing
// a file must not break the build of everyone else)
const complete = (f) => { const t = fs.readFileSync(path.join(dir, f), "utf8"); return /export default T;\s*$/.test(t) && (t.match(/^  "soi\./gm) || []).length >= 300; };
const skipped = [];
const codes = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^[a-z]{2}\.ts$/.test(f)).filter((f) => complete(f) || (skipped.push(f), false)).map((f) => f.slice(0, 2)).sort() : [];
if (skipped.length) console.warn(`⚠ i18n-sign: skipped incomplete file(s): ${skipped.join(" ")}`);
const out = `/**
 * Sign Doc · Session UX in every language (operator 2026-09-09: "all UX translations, 33 languages"). One file per language,
 * loaded on demand when the Globe selects it (the Divinity Guide's LANG_LOADERS pattern, R-CORE); nothing of them rides in the
 * first bundle. EN is the lexicon's englishDefault; ES is lib/lexicon-translations-es-sign.ts (the first full second language).
 * GENERATED by scripts/gen-i18n-index.mjs from the files present — do not edit by hand.
 */
export const SIGN_LOCALES = [${codes.map((c) => `"${c}"`).join(", ")}] as const;
export type SignLocale = (typeof SIGN_LOCALES)[number];
const LOADERS: Record<SignLocale, () => Promise<{ default: Record<string, string> }>> = {
${codes.map((c) => `  ${c}: () => import("./${c}"),`).join("\n")}
};
/** the language's Sign Doc strings, or null when the code has no file (en, es, unknown) */
export async function loadSignLocale(code: string): Promise<Record<string, string> | null> {
  const l = (LOADERS as Record<string, (() => Promise<{ default: Record<string, string> }>) | undefined>)[code];
  if (!l) return null;
  try { return (await l()).default; } catch { return null; }
}
`;
fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(path.join(dir, "index.ts"), out);
console.log(`✓ i18n-sign index: ${codes.length} language files (${codes.join(" ")})`);
