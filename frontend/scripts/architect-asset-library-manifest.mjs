// ARCHITECT-2525 · ASSET LIBRARY MANIFEST — generate the committed TS copy of the operator's COMPLETE 3D asset library
// manifest + per-asset metadata (verbatim), so the registry can build ALL assets at module init without a fetch.
//
//   node scripts/architect-asset-library-manifest.mjs [<library dir>] [<out .ts>]
//   default library dir: ../docs/architecture-2525/asset-library/3d-all-assets-2026-11-07 (relative to frontend/)
//   default out:         lib/architect-2525/assets/library-manifest.ts
//
// Deterministic: the manifest order is kept, each metadata file is parsed and re-emitted as JSON (verbatim values, his key
// order), the source manifest's sha256 + counts are recorded in LIBRARY_SOURCE so a drift between the docs master and the
// committed copy is a gate failure, never a silent one. No Date, no random. Reads only; writes the one .ts.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const FE = path.resolve(HERE, "..");
const LIB = path.resolve(process.argv[2] ?? path.resolve(FE, "../docs/architecture-2525/asset-library/3d-all-assets-2026-11-07"));
const OUT = path.resolve(process.argv[3] ?? path.resolve(FE, "lib/architect-2525/assets/library-manifest.ts"));

const manifestRaw = fs.readFileSync(path.join(LIB, "manifest.json"));
const manifest = JSON.parse(manifestRaw.toString("utf8"));
const sha = crypto.createHash("sha256").update(manifestRaw).digest("hex");
const assets = manifest.assets;
if (!Array.isArray(assets) || assets.length === 0) throw new Error("manifest.assets is empty");

const metadata = {};
for (const a of assets) {
  for (const k of ["id", "label", "model", "metadata", "planSymbol"]) if (typeof a[k] !== "string") throw new Error(`manifest entry ${a.id}: ${k} is not a string`);
  const m = JSON.parse(fs.readFileSync(path.join(LIB, a.metadata), "utf8"));
  if (m.id !== a.id) throw new Error(`metadata id ${m.id} != manifest id ${a.id}`);
  if (Object.hasOwn(metadata, a.id)) throw new Error(`duplicate id ${a.id}`);
  metadata[a.id] = m;
}

// the recorded source is the REPO-canonical location of his library (its basename under docs/architecture-2525/asset-library),
// never the path this run happened to read from — so the output is byte-identical wherever it is generated.
const relLib = `docs/architecture-2525/asset-library/${path.basename(LIB)}`;
const j = (v) => JSON.stringify(v, null, 2);
const ts = `// GENERATED by scripts/architect-asset-library-manifest.mjs — DO NOT EDIT. Regenerate from the operator's library:
//   node scripts/architect-asset-library-manifest.mjs
// Source: ${relLib}/manifest.json (sha256 ${sha}) + metadata/*.json, VERBATIM.
// ${manifest.library ?? ""} · version ${manifest.version ?? "?"} · ${manifest.date ?? "?"} · ${assets.length} assets.
// Concept boards by eXeL AI. Assets are ILLUSTRATIVE; nothing here enters canonical truth.

/** The committed copy's provenance — the gate asserts it against the docs master when that is on disk. */
export const LIBRARY_SOURCE = {
  dir: ${j(relLib)},
  manifestSha256: ${j(sha)},
  library: ${j(manifest.library ?? "")},
  version: ${j(manifest.version ?? "")},
  date: ${j(manifest.date ?? "")},
  coordinateSystem: ${j(manifest.coordinateSystem ?? "")},
  units: ${j(manifest.units ?? "")},
  pivotConvention: ${j(manifest.pivotConvention ?? "")},
  assetCount: ${assets.length},
  boardPlacementCount: ${Number(manifest.boardPlacementCount ?? 0)},
} as const;

/** One manifest row — paths are relative to the library root (models/<stem>.glb · metadata/<stem>.json · plan/<stem>.svg). */
export interface LibraryManifestEntry { id: string; label: string; packs: number[]; model: string; metadata: string; planSymbol: string }

/** His per-asset metadata, verbatim (schemaVersion 1.0). \`model\`/\`planSymbol\` here are relative to metadata/ (../models/…). */
export interface LibraryMetadata {
  schemaVersion: string;
  id: string;
  label: string;
  packs: number[];
  sections: string[];
  sourcePlacementIds: string[];
  model: string;
  planSymbol: string;
  dimensionsM: { width: number; depth: number; height: number };
  pivot: { origin: string; axes: string };
  rotation: { axis: string; freeRotation: boolean; allowedDegrees: number[] };
  mounting: string;
  snap: string[];
  authority: string;
  modelQuality: string;
  materialRule: string;
  rebuildSpec: { preserveSemanticId: boolean; preservePivotContract: boolean; preservePlacementContract: boolean };
}

export const LIBRARY_MANIFEST: LibraryManifestEntry[] = ${j(assets.map((a) => ({ id: a.id, label: a.label, packs: Array.isArray(a.packs) ? a.packs : [], model: a.model, metadata: a.metadata, planSymbol: a.planSymbol })))};

export const LIBRARY_METADATA: Record<string, LibraryMetadata> = ${j(metadata)};
`;
fs.writeFileSync(OUT, ts);
console.log(`wrote ${path.relative(FE, OUT)} · ${assets.length} assets · manifest sha256 ${sha}`);
