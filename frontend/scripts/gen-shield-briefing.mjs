/*
 * gen-shield-briefing — docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md is DERIVED, never hand-written.
 *
 * WHY THIS EXISTS (DD-128 / DD-129, 2026-10-19). The whitepaper copy of "Shield in the Sky" was hand-made
 * three times in one day and each time it was labelled "gateable source for Asar's five lines" while holding
 * ZERO of them (grep -c "Primary missile threat destroyed" → 0), and the last edit cut it from 17,634 B to
 * 5,424 B. Nothing could see it, because the only pinned copy lives in docs/asks/ and nothing bound the two.
 *
 * THE CLASS, FIXED: the whitepaper copy is rendered FROM the pinned verbatim paste
 * (docs/asks/2026.10.19_Shield_in_the_Sky_ADA_Briefing.md, sha256 in its sidecar, verified by asks-persist
 * every run). Only page furniture is dropped — the running title/subtitle pair, "Prepared By",
 * "Accelerating Human Intelligence", "N | Page" — and the asks file's own ">" header block. Every sentence
 * of the paper survives: the nine beats, Asar's Synthesis with the five lines, the ending, and the back
 * matter with ATP 3-01.81 and FM 3-12. tests/whitepaper-source.test.mjs holds the derivation (--check) and
 * the content, so a hand edit of either file turns CI red.
 *
 *   node scripts/gen-shield-briefing.mjs           re-render and write
 *   node scripts/gen-shield-briefing.mjs --check   exit 1 if the committed file differs; writes nothing
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, "..", "..");
export const SRC = path.join(ROOT, "docs/asks/2026.10.19_Shield_in_the_Sky_ADA_Briefing.md");
export const OUT = path.join(ROOT, "docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md");

// Page furniture — matched on the WHOLE line, so a sentence that merely contains these words is kept.
const FURNITURE = [
  /^Shield in the Sky$/,
  /^Air Defense Leadership and Troops AI & Technology Briefing$/,
  /^Prepared By$/,
  /^Accelerating Human Intelligence$/,
  /^\d+ \| Page$/,
  /^￼$/, // the object-replacement glyph the paste carried where a picture sat
];

export function render() {
  const raw = fs.readFileSync(SRC, "utf8");
  const sha = createHash("sha256").update(raw).digest("hex");
  const lines = raw.split("\n");
  const body = [];
  let inHeader = true; // the asks file opens with the H1, then a "> …" block and a "---": that block is ours, not the paper's
  for (const ln of lines) {
    if (inHeader) {
      if (/^# /.test(ln)) { body.push(ln); continue; }
      if (/^> ?/.test(ln) || ln.trim() === "") continue;
      if (ln.trim() === "---") { inHeader = false; continue; }
      inHeader = false; // first real line
    }
    if (FURNITURE.some((re) => re.test(ln.trim()))) continue;
    body.push(ln);
  }
  // collapse runs of blank lines to one (the furniture left holes)
  const text = body.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";

  const header = [
    "<!-- GENERATED by frontend/scripts/gen-shield-briefing.mjs from docs/asks/2026.10.19_Shield_in_the_Sky_ADA_Briefing.md.",
    "     Do not edit by hand: re-run the generator. tests/whitepaper-source.test.mjs fails CI on any drift. -->",
    "",
    "> **Shield in the Sky — text of record, page furniture removed.** Source: `docs/asks/2026.10.19_Shield_in_the_Sky_ADA_Briefing.md`",
    `> (his verbatim paste of paper #2, sha256 \`${sha.slice(0, 16)}…\`, pinned in its sidecar and verified by \`asks-persist\` every run).`,
    "> This file is DERIVED from it and carries every sentence of the paper — the nine beats, Asar's Synthesis with the five",
    "> scored lines, the ending, and the back matter with ATP 3-01.81 and FM 3-12. Images are in `Shield_in_the_Sky_Images.md`",
    "> (slots 1–13; none in the repo yet). The Vision-2525 whitepaper beside it is a different document.",
    "",
    "| Item | Location |",
    "|------|----------|",
    "| This text (generated, gated) | `docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md` |",
    "| Images companion (slots 1–13) | `docs/whitepaper/Shield_in_the_Sky_Images.md` |",
    "| Source of record | `docs/asks/2026.10.19_Shield_in_the_Sky_ADA_Briefing.md` |",
    "| Vision-2525 PDF (git) | `docs/whitepaper/VISION-2525.pdf` |",
    "| Vision-2525 PDF (Supabase) | https://ppgfjplawtlrfqpnszyb.supabase.co/storage/v1/object/public/whitepaper/VISION-2525.pdf |",
    "| Vision-2525 summaries | `docs/whitepaper/2026-10-14_VISION-2525_summaries_333.md` |",
    "| Whitepaper index | `docs/whitepaper/README.md` |",
    "",
    "---",
    "",
  ].join("\n");
  return header + text;
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const CHECK = process.argv.includes("--check");
  const want = render();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
  if (CHECK) {
    if (cur !== want) { console.error("STALE  docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md — re-run node scripts/gen-shield-briefing.mjs"); process.exit(1); }
    console.log("gen-shield-briefing --check OK · the whitepaper copy is the pinned paper, furniture removed");
  } else {
    fs.writeFileSync(OUT, want);
    console.log(`gen-shield-briefing OK · wrote ${Buffer.byteLength(want)} B to docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md`);
  }
}
