// whitepaper-source — THE WHITEPAPER COPY OF "SHIELD IN THE SKY" IS THE PAPER, AND ITS LINKS RESOLVE.
//
// Written 2026-10-19 (DD-128 / DD-129) after the hand-made copy was labelled "gateable source for Asar's five
// lines" three times in one day while holding none of them, shrank to a stub, and carried fifteen image links
// to files not in the repo with a caption naming the wrong PDF. No gate could see any of it. This one can:
//   1. the file equals what gen-shield-briefing renders from the pinned docs/asks/ paste (no drift either way);
//   2. the five scored lines are present verbatim — the ladder is gated on them;
//   3. the two manuals this paper is the only source for are present (ATP 3-01.81, FM 3-12);
//   4. all nine beat headings are present;
//   5. every markdown image link in docs/whitepaper/*.md points at a file that exists in the repo.
// Pure fs — no git, no browser.
import fs from 'node:fs';
import path from 'node:path';
import { render, OUT, ROOT } from '../scripts/gen-shield-briefing.mjs';

let pass = 0, fail = 0;
const ok = (c, m) => { if (c) pass++; else { fail++; console.log('FAIL:', m); } };

const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
ok(cur.length > 0, 'docs/whitepaper/Shield_in_the_Sky_ADA_Briefing.md exists');
ok(cur === render(), 'the whitepaper copy is exactly what gen-shield-briefing renders from the pinned docs/asks paste (no hand edits, no drift)');

const FIVE = [
  'Primary missile threat destroyed',
  'Low-altitude attackers eliminated',
  'Drone swarm neutralized',
  'Joint network stable',
  'Defended assets preserved',
];
// The paste keeps the PDF's own line wraps (verbatim is the law), and one of the five breaks across a line
// ("Low-altitude attackers" / "eliminated"). So each line is matched word for word with ANY whitespace between
// words — the sentence is verbatim; only the wrap is the printer's.
const words = (t) => new RegExp(t.split(/\s+/).map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('\\s+'));
for (const l of FIVE) ok(words(l).test(cur), `the five lines — "${l}" is in the whitepaper copy word for word`);
ok(cur.includes('All threads complete'), 'Asar\'s Synthesis is carried in full ("All threads complete")');
ok(cur.includes('FULL X-BAT SWARM SCENARIO LOADING'), 'the ending is carried — the swarm package loads only after the five lines');
ok(cur.includes('ATP 3-01.81'), 'the back matter names ATP 3-01.81 (Counter-UAS) — this paper is our only source for it');
ok(cur.includes('FM 3-12'), 'the back matter names FM 3-12 (EW) — this paper is our only source for it');
for (const h of ["Enki's Spark", "Thor's Shield", "Krishna's Thread", "Odin's Eye", "Enlil's Order", "Athena's Direction", "Sofia's Lens", "Aset's Echo", "Asar's Synthesis"]) {
  const esc = h.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/'/g, "['’]"); // escape FIRST, then let either apostrophe match
  ok(new RegExp('^## ' + esc + '\\s*$', 'm').test(cur), `beat heading "## ${h}" is present`);
}
ok(!/\bPrepared By\b\s*$/m.test(cur) && !/^\d+ \| Page$/m.test(cur), 'page furniture is removed (no "Prepared By" / "N | Page" lines)');
ok(cur.includes('GENERATED by frontend/scripts/gen-shield-briefing.mjs'), 'the file declares itself generated, with the generator named');

// 5. every image link in docs/whitepaper/*.md resolves to a file in the repo
const WP = path.join(ROOT, 'docs/whitepaper');
let links = 0, broken = [];
for (const f of fs.readdirSync(WP).filter((x) => x.endsWith('.md'))) {
  const src = fs.readFileSync(path.join(WP, f), 'utf8');
  for (const m of src.matchAll(/!\[[^\]]*\]\(([^)\s]+)\)/g)) {
    links++;
    const target = m[1];
    if (/^https?:\/\//.test(target)) continue; // external — not this gate's business
    const p = path.resolve(WP, target);
    if (!fs.existsSync(p)) broken.push(`${f} → ${target}`);
  }
}
ok(broken.length === 0, `every image link in docs/whitepaper/*.md points at a file in the repo (${links} links, ${broken.length} broken${broken.length ? ': ' + broken.slice(0, 4).join(' · ') + (broken.length > 4 ? ' …' : '') : ''})`);

const img = fs.readFileSync(path.join(WP, 'Shield_in_the_Sky_Images.md'), 'utf8');
ok(!/pulled from the Vision-2525 PDF|extracts from the Vision-2525 PDF/i.test(img), 'the images companion does not claim its Shield extracts come from the Vision-2525 PDF (a different paper)');

console.log(`\nwhitepaper-source: ${pass} passed, ${fail} failed · the whitepaper copy is the pinned paper, furniture removed; ${links} image links checked`);
process.exit(fail ? 1 : 0);
